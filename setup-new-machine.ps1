<#
  Give every Cline (and Claude Code) task on this PC the Eskimo QC context.
  For a PC that ALREADY has pg4-ai-workflow. Paths of this PC are written into the rule files.

  Why: Cline does not read ~/.claude/CLAUDE.md. It auto-loads, in EVERY task:
    - global rules:     <Documents>\Cline\Rules\*.md
    - global workflows: <Documents>\Cline\Workflows\*.md   (typed as /qa-auto.md in the Cline chat)

  Usage (PowerShell, from the kit folder):
    powershell -ExecutionPolicy Bypass -File .\setup-new-machine.ps1
    powershell -ExecutionPolicy Bypass -File .\setup-new-machine.ps1 -Pg4 E:\src\pg4-ai-workflow -E2E E:\src\eskimo-e2e
    ... -OllamaCtx 32768      # local Ollama: raise the default context window (see README)

  Safe to re-run: existing eskimo-e2e and .env are kept; only the eskimo-qc files/blocks are rewritten.
#>
param(
  [string]$Pg4,
  [string]$E2E,
  [int]$OllamaCtx = 0
)
$ErrorActionPreference = 'Stop'
$kit  = $PSScriptRoot
$todo = New-Object System.Collections.Generic.List[string]
function Step($m) { Write-Host "`n== $m" -ForegroundColor Cyan }
function Has($c)  { [bool](Get-Command $c -ErrorAction SilentlyContinue) }
function WriteUtf8($path, $text) { [IO.File]::WriteAllText($path, $text, (New-Object Text.UTF8Encoding $false)) }

# 1. Find pg4-ai-workflow ----------------------------------------------------------------------
Step '1. pg4-ai-workflow'
if (-not $Pg4) {
  $Pg4 = @('D:\pg4-ai-workflow', 'C:\pg4-ai-workflow', 'E:\pg4-ai-workflow', "$HOME\pg4-ai-workflow",
           "$HOME\source\repos\pg4-ai-workflow", "$HOME\Documents\pg4-ai-workflow") |
         Where-Object { Test-Path "$_\claude\commands\qa-auto.md" } | Select-Object -First 1
}
if (-not $Pg4 -or -not (Test-Path "$Pg4\claude\commands\qa-auto.md")) {
  throw 'pg4-ai-workflow not found. Re-run with -Pg4 <folder that contains claude\commands\qa-auto.md>'
}
$Pg4 = (Resolve-Path $Pg4).Path.TrimEnd('\')
Write-Host "  [ok] $Pg4"

# 2. eskimo-e2e (Playwright project) -----------------------------------------------------------
if (-not $E2E) { $E2E = Join-Path (Split-Path $Pg4 -Parent) 'eskimo-e2e' }
Step "2. eskimo-e2e -> $E2E"
if (Test-Path "$E2E\package.json") { Write-Host '  [ok] exists, kept as is' }
else {
  $parent = Split-Path $E2E -Parent
  New-Item -ItemType Directory -Force $parent | Out-Null
  Expand-Archive "$kit\eskimo-e2e.zip" -DestinationPath $parent
  if ((Split-Path $E2E -Leaf) -ne 'eskimo-e2e') { Rename-Item (Join-Path $parent 'eskimo-e2e') (Split-Path $E2E -Leaf) }
  Push-Location $E2E
  if (Has 'npm') { npm ci; npx playwright install chromium } else { $todo.Add("Install Node.js LTS, then in $E2E run: npm ci; npx playwright install chromium") }
  Pop-Location
}
if (-not (Test-Path "$E2E\.env")) { Copy-Item "$E2E\.env.example" "$E2E\.env"; $todo.Add("Fill test accounts in $E2E\.env (names in .env.example)") }
$E2E = (Resolve-Path $E2E).Path.TrimEnd('\')

# 3. Rule text with this PC's paths ------------------------------------------------------------
$rules = (Get-Content "$kit\personal-claude-md.template.md" -Raw -Encoding UTF8).Replace('{{PG4}}', $Pg4).Replace('{{E2E}}', $E2E)

# 4. Cline: global rule + /qa-auto.md workflow -------------------------------------------------
$docs = [Environment]::GetFolderPath('MyDocuments')     # follows OneDrive redirection
Step "3. Cline rules/workflows in $docs\Cline"
New-Item -ItemType Directory -Force "$docs\Cline\Rules", "$docs\Cline\Workflows" | Out-Null
WriteUtf8 "$docs\Cline\Rules\eskimo-qc.md" ("# Eskimo QC context (generated by setup-new-machine.ps1 - re-run it instead of editing)`n`n" + $rules)
# Pointer only (no copy): the team updates qa-auto.md in pg4-ai-workflow, Cline always reads the current file.
WriteUtf8 "$docs\Cline\Workflows\qa-auto.md" (@"
# /qa-auto - QC a Plane work item

1. FIRST read the whole file ``$Pg4\claude\commands\qa-auto.md`` with your file-read tool.
   It is the source of truth and changes often: read it again in every task, never work from memory.
2. Follow it step by step, with the arguments the user typed after /qa-auto.md
   (item ID, optional test-case file, --url, --manual, --rerun).
3. E2E project: ``$E2E``. Rules and plane CLI invocation: Cline\Rules\eskimo-qc.md.
4. Stop and wait for the user's "yes" where qa-auto.md says so (before running tests, before any Plane write).
"@)
Write-Host '  [ok] Rules\eskimo-qc.md, Workflows\qa-auto.md'

# 5. Claude Code: same block in ~/.claude/CLAUDE.md (harmless if Claude Code is not used) -------
Step '4. ~/.claude/CLAUDE.md block'
$md    = Join-Path $HOME '.claude\CLAUDE.md'
$begin = '<!-- eskimo-qc:begin (managed by setup-new-machine.ps1, edits are overwritten) -->'
$end   = '<!-- eskimo-qc:end -->'
New-Item -ItemType Directory -Force (Split-Path $md) | Out-Null
$old = if (Test-Path $md) { Get-Content $md -Raw -Encoding UTF8 } else { '' }
$old = [regex]::Replace($old, '(?s)\r?\n?' + [regex]::Escape($begin) + '.*?' + [regex]::Escape($end) + '\r?\n?', "`n")
WriteUtf8 $md ($old.TrimEnd() + "`n`n$begin`n$($rules.TrimEnd())`n$end`n")
Write-Host '  [ok]'

# 6. Local Ollama context window (optional) ----------------------------------------------------
if ($OllamaCtx -gt 0) {
  Step "5. OLLAMA_CONTEXT_LENGTH = $OllamaCtx (user env var)"
  [Environment]::SetEnvironmentVariable('OLLAMA_CONTEXT_LENGTH', "$OllamaCtx", 'User')
  $todo.Add('Quit Ollama from the tray and start it again (picks up OLLAMA_CONTEXT_LENGTH)')
  $todo.Add("In Cline settings (provider Ollama) set the context window to $OllamaCtx too")
}

# 7. Check -------------------------------------------------------------------------------------
Step 'Check'
if (Has 'plane') {
  plane auth status *> $null
  if ($LASTEXITCODE -eq 0) { Write-Host '  [ok] plane logged in' } else { $todo.Add('Run: plane auth login') }
} else { $todo.Add("plane not on PATH: in Git Bash run  cd '$Pg4' && bash claude/install-commands.sh  then open a new terminal") }
$todo.Add('Cline: open the Rules popover (scale icon under the chat box) and check eskimo-qc.md is ON')
$todo.Add('Start a NEW Cline task (old tasks keep their old context), then type: /qa-auto.md ESKIMO-<n> --url <stage url>')

Write-Host "`nTODO:" -ForegroundColor Yellow
$todo | ForEach-Object { Write-Host "  - $_" }
